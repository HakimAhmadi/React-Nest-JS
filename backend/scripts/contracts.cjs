require('reflect-metadata');
const fs = require('node:fs');
const path = require('node:path');
const { Module } = require('@nestjs/common');
const { NestFactory } = require('@nestjs/core');
const { SwaggerModule, DocumentBuilder } = require('@nestjs/swagger');

require('ts-node').register({
  project: path.resolve(__dirname, '../tsconfig.json'),
  transpileOnly: true,
});

const { responseModels } = require('../src/contracts/responses');

async function generate() {
  class ContractsModule {}
  Module({})(ContractsModule);
  const app = await NestFactory.create(ContractsModule, {
    logger: false,
    abortOnError: false,
  });

  let schemas;
  try {
    const document = SwaggerModule.createDocument(
      app,
      new DocumentBuilder()
        .setTitle('Boilerplate API contracts')
        .setVersion('1.0')
        .build(),
      { extraModels: responseModels },
    );
    schemas = document.components?.schemas || {};
  } finally {
    await app.close();
  }

  function type(schema) {
    let value;
    if (schema.$ref) {
      value = schema.$ref.split('/').at(-1);
    } else if (schema.enum) {
      value = schema.enum.map((item) => JSON.stringify(item)).join(' | ');
    } else if (schema.allOf) {
      value = schema.allOf.map(type).join(' & ');
    } else if (schema.oneOf) {
      value = schema.oneOf.map(type).join(' | ');
    } else if (schema.type === 'array') {
      value = `Array<${type(schema.items || {})}>`;
    } else if (schema.type === 'integer' || schema.type === 'number') {
      value = 'number';
    } else if (schema.type === 'string' || schema.type === 'boolean') {
      value = schema.type;
    } else if (schema.properties) {
      value = `{ ${Object.entries(schema.properties)
        .map(
          ([key, item]) =>
            `${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: ${type(item)};`,
        )
        .join(' ')} }`;
    } else {
      value = 'unknown';
    }
    return schema.nullable ? `(${value}) | null` : value;
  }

  const types =
    '// Generated by backend/scripts/contracts.cjs. Edit backend/src/contracts/responses.ts.\n\n' +
    Object.entries(schemas)
      .map(([name, schema]) => `export type ${name} = ${type(schema)};`)
      .join('\n\n') +
    '\n';

  const outputs = [
    ['../../frontend/src/contracts/api.generated.d.ts', types],
    [
      '../../frontend/src/contracts/schemas.generated.json',
      JSON.stringify(schemas, null, 2) + '\n',
    ],
  ];

  for (const [relative, value] of outputs) {
    const file = path.resolve(__dirname, relative);
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== value) {
        throw new Error(
          'Generated API contracts are stale. Run npm run contracts:generate in backend.',
        );
      }
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, value);
    }
  }

  console.log(
    JSON.stringify({
      status: process.argv.includes('--check')
        ? 'contracts_current'
        : 'contracts_generated',
      models: Object.keys(schemas).length,
    }),
  );
}

generate().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
